#!/usr/bin/env python3
"""Write the constants from shared/rig.json into every port.

Each port keeps a marked block that this script owns:
  shared/Rig.hpp               (Windows + Linux)   // <rig:generated> ... // </rig:generated>
  Sources/CatPhysics.swift     (macOS)             // <rig:generated> ... // </rig:generated>
  homepage/pet/renderer.js     (kurocat.cc pet)    // <rig:generated> ... // </rig:generated>
  <workshop>/renderer.js       (KuroCat-Workshop, sibling repo, when found or given with --workshop)

Usage:
  python3 scripts/gen-rig.py            rewrite the blocks
  python3 scripts/gen-rig.py --check    exit 1 if any block is stale (CI)
"""
import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BEGIN, END = '<rig:generated>', '</rig:generated>'
NOTE = 'generated by scripts/gen-rig.py from shared/rig.json; edit that file, not this block'


def load():
    rig = json.loads((ROOT / 'shared/rig.json').read_text(encoding='utf-8'))
    ht, hs, bd = rig['headTurn'], rig['headSurface'], rig['bodyDeform']
    # Order matters only for readability of the generated blocks.
    return [
        ('canvasWidth', rig['canvas']['width']), ('canvasHeight', rig['canvas']['height']),
        ('seatX', rig['seatAnchor']['x']), ('seatY', rig['seatAnchor']['y']),
        ('yawPerUnit', ht['yawPerUnit']), ('pitchPerUnit', ht['pitchPerUnit']),
        ('maxHeadYaw', ht['maxHeadYaw']), ('headShiftPerYaw', ht['headShiftPerYaw']),
        ('domeRadiusX', hs['domeRadiusX']), ('domeRadiusY', hs['domeRadiusY']),
        ('domeDepth', hs['domeDepth']), ('planeDepth', hs['planeDepth']),
        ('lieSquash', bd['lieSquash']), ('squashWiden', bd['squashWiden']), ('lieWiden', bd['lieWiden']),
    ]


def num(v):
    s = repr(float(v))
    return s[:-2] + '.0' if s.endswith('.0') else s


def cpp_block(consts):
    lines = [f'// {BEGIN} {NOTE}']
    for k, v in consts:
        lines.append(f'constexpr float {k[0].upper() + k[1:]} = {num(v)}f;')
    lines.append(f'// {END}')
    return '\n'.join(lines)


def swift_block(consts):
    lines = [f'// {BEGIN} {NOTE}', 'enum KuroRig {']
    for k, v in consts:
        lines.append(f'    static let {k}: CGFloat = {num(v)}')
    lines += ['}', f'// {END}']
    return '\n'.join(lines)


def js_block(consts, indent='  '):
    body = ', '.join(f'{k}: {num(v)}' for k, v in consts)
    return '\n'.join([f'{indent}// {BEGIN} {NOTE}', f'{indent}const RIG = Object.freeze({{ {body} }});', f'{indent}// {END}'])


BLOCK_RE = re.compile(r'[ \t]*// ' + re.escape(BEGIN) + r'.*?// ' + re.escape(END), re.S)


def apply(text, block, insert):
    """Replace the existing block, or insert one with `insert(text, block)` when the file has none."""
    if BLOCK_RE.search(text):
        return BLOCK_RE.sub(lambda _m: block, text, count=1)
    return insert(text, block)


def after_use_strict(text, block):
    m = re.search(r"^\s*'use strict';\s*$", text, re.M)
    if not m:
        raise SystemExit("no 'use strict'; line to put the RIG block after")
    return text[:m.end()] + '\n\n' + block + '\n' + text[m.end():]


def append_end(text, block):
    return text.rstrip('\n') + '\n\n' + block + '\n'


def cpp_insert(text, block):
    raise SystemExit('shared/Rig.hpp has no generated block; restore it from git')


def targets(workshop):
    out = [
        (ROOT / 'shared/Rig.hpp', cpp_block, cpp_insert),
        (ROOT / 'Sources/CatPhysics.swift', swift_block, append_end),
        (ROOT / 'homepage/pet/renderer.js', js_block, after_use_strict),
    ]
    if workshop:
        out.append((workshop / 'renderer.js', js_block, after_use_strict))
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--check', action='store_true')
    ap.add_argument('--workshop', type=Path, help='KuroCat-Workshop checkout (default: ../KuroCat-Workshop when present)')
    args = ap.parse_args()
    workshop = args.workshop or (ROOT.parent / 'KuroCat-Workshop')
    if not (workshop / 'renderer.js').exists():
        if args.workshop:
            raise SystemExit(f'{workshop}/renderer.js not found')
        workshop = None
    consts = load()
    stale = []
    for path, make, insert in targets(workshop):
        text = path.read_text(encoding='utf-8')
        new = apply(text, make(consts), insert)
        if new != text:
            stale.append(path)
            if not args.check:
                path.write_text(new, encoding='utf-8')
    if args.check:
        for p in stale:
            print(f'stale rig block: {p} (run python3 scripts/gen-rig.py)', file=sys.stderr)
        sys.exit(1 if stale else 0)
    for p in stale:
        print(f'updated {p}')


if __name__ == '__main__':
    main()
